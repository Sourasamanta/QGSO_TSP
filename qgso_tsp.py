def exact_tsp(distance):
    cities_to_visit = list(range(1, len(distance)))

    best_tour = None
    best_distance = float("inf")

    for permutation in itertools.permutations(cities_to_visit):

        tour = [0] + list(permutation)
        d = tour_length(tour, distance)

        if d < best_distance:
            best_distance = d
            best_tour = tour.copy()

    return best_tour, best_distance

