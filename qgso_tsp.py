def quantum_gravitational_search_tsp(
    distance,
    population_size=20,
    iterations=50,
    mutation_rate=0.20
):
    n = len(distance)

    population = create_population(
        population_size,
        n
    )

    best_tour = None
    best_distance = float("inf")
    convergence = []
    decision_history = []

    quantum_circuit_count = 0
    hermitian_valid = True
    unitary_valid = True

    for iteration in range(iterations):

        fitness = [
            tour_length(tour, distance)
            for tour in population
        ]

        best_index = int(np.argmin(fitness))

        if fitness[best_index] < best_distance:
            best_distance = fitness[best_index]
            best_tour = population[best_index].copy()

        masses = calculate_masses(fitness)

        for mass in masses:

            H = create_mass_hamiltonian(mass)
            U = create_unitary_operator(mass)

            hermitian_valid &= check_hermitian(H)
            unitary_valid &= check_unitary(U)

        decisions, circuit = quantum_gravitational_measurement(masses)

        quantum_circuit_count += 1
        decision_history.extend(decisions.tolist())

        k = max(
            2,
            int(
                population_size *
                (1 - iteration / iterations)
            )
        )

        strongest = sorted(
            range(population_size),
            key=lambda i: fitness[i]
        )[:k]

        new_population = []

        for i in range(population_size):

            agent = population[i].copy()
            quantum_decision = decisions[i]

            for j in strongest:

                if i == j:
                    continue

                gravitational_strength = masses[j]

                if quantum_decision == 1:

                    if random.random() < gravitational_strength:

                        agent = quantum_move_towards(
                            agent,
                            population[j],
                            quantum_decision
                        )

            if random.random() < mutation_rate:
                agent = mutate(agent)

            new_population.append(agent)

        population = new_population
        convergence.append(best_distance)

    return {
        "tour": best_tour,
        "distance": best_distance,
        "convergence": convergence,
        "decisions": decision_history,
        "hermitian": hermitian_valid,
        "unitary": unitary_valid,
        "quantum_circuits": quantum_circuit_count,
        "quantum_qubits": population_size
    }

